def bom_table(c, x, y_top, groups, start_no):
    data = [['№', 'Наименование', 'Ед.', 'Кол.', 'Примечание']]
    cmds = [('FONT', (0, 0), (-1, 0), FB, 5.8), ('BACKGROUND', (0, 0), (-1, 0), HexColor('#E7EDF1')),
            ('ALIGN', (2, 0), (3, -1), 'CENTER')]
    no = start_no
    for g, rows in groups:
        data.append(['', g, '', '', ''])
        r = len(data) - 1
        cmds += [('SPAN', (1, r), (4, r)), ('FONT', (0, r), (-1, r), FB, 6.0),
                 ('TEXTCOLOR', (0, r), (-1, r), ACCENT), ('TOPPADDING', (0, r), (-1, r), 2.6)]
        for (name, unit, qty, note) in rows:
            data.append([str(no), name, unit, qty, note])
            no += 1
    h = table(c, x, y_top, data, [7, 62, 13, 10, 41], cmds, font_size=5.6, pad=1.15)
    return no


