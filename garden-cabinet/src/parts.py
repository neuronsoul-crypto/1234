STOCK = 3000


def pack(lengths, stock, kerf=5):
    bins = []
    for L in sorted(lengths, reverse=True):
        for b in bins:
            if sum(b) + kerf * len(b) + L <= stock:
                b.append(L)
                break
        else:
            bins.append([L])
    return bins


