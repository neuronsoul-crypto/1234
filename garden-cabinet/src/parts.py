STOCK = {'45×95': 3000, '45×45': 3000, '28×95': 3000, '20×95': 3000, '20×120': 3000, '20×145': 3000,
         '20×45': 3000, '20×140': 3000}
STOCK_DOOR = 6000   # имитация бруса в Крыму — длиной 3 и 6 м; из 6 м выходит 3 детали


def pack(lengths, stock, kerf=5):
    """Раскрой «первый подходящий по убыванию». Возвращает список хлыстов (списки длин)."""
    bins = []
    for L in sorted(lengths, reverse=True):
        for b in bins:
            if sum(b) + kerf * len(b) + L <= stock:
                b.append(L)
                break
        else:
            bins.append([L])
    return bins


def purchase():
    """Сводка по сечениям: общая длина, число хлыстов, хлыстов с запасом."""
    groups = {}
    for (pos, name, sec, L, n, grp, note) in PARTS + CLAD_PARTS:
        key = sec
        if pos == '25':
            key = '20×145 (имитация бруса)'
        groups.setdefault(key, []).extend([L] * n)
    out = []
    for key, Ls in groups.items():
        sec = key.split(' ')[0]
        stock = STOCK_DOOR if key.startswith('20×145 (') else STOCK.get(sec, 3000)
        bins = pack(Ls, stock)
        total = sum(Ls)
        n = len(bins)
        n_res = n + (math.ceil(n * 0.1) if n >= 4 else 0)
        out.append((key, total / 1000.0, stock, n, n_res, bins))
    order = ['45×95', '45×45', '28×95', '20×140', '20×95', '20×120', '20×145', '20×145 (имитация бруса)', '20×45']
    out.sort(key=lambda r: order.index(r[0]) if r[0] in order else 99)
    return out


