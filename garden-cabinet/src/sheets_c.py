    tblock(c, num, total, 'Проверка, обслуживание, варианты', '—')
    heading(c, num, 'Проверка на протечки, обслуживание, варианты')
    x1, x2 = 20, 156
    text(c, x1, 182, 'Тест на протечки (сразу после сборки)', 8.5, FB, ACCENT)
    h = para(c, x1, 179.5, 128,
             '1. Закрыть двери, на пол положить сухой картон.<br/>'
             '2. 10 минут поливать из шланга: кровлю, стык с домом, затем двери и стены — снизу вверх, '
             'как косой дождь.<br/>'
             '3. Открыть, проверить картон, стены, стык кровли с домом изнутри, порог.<br/>'
             '4. Течёт — искать выше по ходу воды: герметик над планкой, саморез без шайбы, '
             'уплотнитель (полоска бумаги при закрытой двери должна зажиматься).', PS)
    y = 179.5 - h - 7
    text(c, x1, y, 'Обслуживание', 8.5, FB)
    data = [['Когда', 'Что сделать'],
            ['Весна', 'Осмотреть герметик над планкой примыкания, подтянуть саморезы, смазать петли и шпингалеты.'],
            ['Лето', 'Проветрить шкаф в сухой день; подсыпать щебень, если проросла трава.'],
            ['Осень', 'Смести листья с кровли, очистить и смазать инструмент перед зимой.'],
            ['Раз в 3–5 лет', 'Обновить герметик и уплотнитель; царапины на профнастиле подкрасить '
                              'аэрозолем в цвет.']]
    data = [[Paragraph(a, PSb), Paragraph(b, PS)] for (a, b) in data]
    cmds = [('BACKGROUND', (0, 0), (-1, 0), HexColor('#E7EDF1'))]
    table(c, x1, y - 2.5, data, [22, 106], cmds, font_size=6.2, pad=1.6)

    text(c, x2, 182, 'Варианты', 8.5, FB)
    para(c, x2, 179.5, 132,
         '<b>Шире — 1.5 м.</b> Ещё 3 листа профнастила и ~6 м бруска: +4.3 тыс. ₽, итого около 22 тыс. — '
         'выходит за бюджет. Створки тогда по 750 мм, каждая из целого листа.<br/><br/>'
         '<b>Ещё дешевле.</b> Оцинкованный профнастил С8 вместо крашеного (−1.4 тыс.), самовывоз '
         '(−1.5 тыс.) — около 15 тыс. ₽.<br/><br/>'
         '<b>Деревянный дом или сайдинг.</b> Вместо рамных дюбелей — саморезы 8×120 в брус/каркас дома; '
         'планку примыкания заводить под сайдинг. Зазор 40 мм обязателен.<br/><br/>'
         '<b>Ниже по высоте.</b> Для инструмента до 1.5 м все стойки можно укоротить на 200 мм; '
         'листы стен и дверей — тоже на 200 мм.<br/><br/>'
         '<b>Шумит в дождь.</b> Это свойство профнастила; для шкафа не важно.<br/><br/>'
         '<b>Конденсат под кровлей.</b> В Крыму бывает весной и осенью. Помогают продух над дверями и '
         'отверстия в полу — не закрывайте их. Мокрый инструмент не ставить вплотную к стенам.', PS)
