def sheet_spec(c, num, total):
    tblock(c, num, total, 'Спецификация и раскрой', '—')
    heading(c, num, 'Спецификация материалов и раскрой', 'Количества — на один шкаф. Цены — на листе 11')
    data = [['№', 'Наименование', 'Ед.', 'Кол.']]
    cmds = [('FONT', (0, 0), (-1, 0), FB, 5.8), ('BACKGROUND', (0, 0), (-1, 0), HexColor('#E7EDF1')),
            ('ALIGN', (2, 0), (3, -1), 'CENTER')]
    no = 1
    for g, rows in PR.groups():
        data.append(['', g, '', ''])
        r = len(data) - 1
        cmds += [('SPAN', (1, r), (3, r)), ('FONT', (0, r), (-1, r), FB, 6.0),
                 ('TEXTCOLOR', (0, r), (-1, r), ACCENT), ('TOPPADDING', (0, r), (-1, r), 2.4)]
        for (name, unit, q, p, src, note) in rows:
            data.append([str(no), name, unit, ('%g' % q).replace('.', ',')])
            no += 1
    table(c, 18, 186, data, [7, 82, 11, 12], cmds, font_size=5.8, pad=1.15)

    x0 = 140
    text(c, x0, 184, 'Раскрой бруска 45×45 (длины после торцовки, мм)', 7.5, FB)
    data = [['Поз.', 'Наименование', 'Длина', 'Кол.', 'Примечание']]
    for (pos, name, sec, L, n, g, note) in PARTS:
        data.append([pos, name, '%d' % round(L), str(n), note])
    for (pos, name, size, n, note) in SHEETS:
        data.append([pos, name, size, str(n), note])
    cmds = [('FONT', (0, 0), (-1, 0), FB, 5.8), ('BACKGROUND', (0, 0), (-1, 0), HexColor('#E7EDF1')),
            ('ALIGN', (2, 0), (3, -1), 'CENTER'), ('ALIGN', (0, 0), (0, -1), 'CENTER')]
    h = table(c, x0, 181, data, [8, 52, 18, 8, 62], cmds, font_size=5.5, pad=0.9)
    y = 181 - h - 7
    Ls, b3, b6 = lumber()
    text(c, x0, y, 'Схема раскроя: %d хлыстов по 3 м (+1 в запас)' % len(b3), 6.8, FB)
    pos_of = {}
    for (pos, name, sec, L, n, g, note) in PARTS:
        pos_of.setdefault(round(L), pos)
    k = 120 / 3000.0
    for i, bn in enumerate(b3):
        yy = y - 4.6 - i * 4.4
        c.saveState()
        c.setFillColor(HexColor('#F3F4F6'))
        c.setStrokeColor(GREY)
        c.setLineWidth(0.3)
        c.rect(x0 * mm, yy * mm, 3000 * k * mm, 3.2 * mm, stroke=1, fill=1)
        xx = x0
        for L in bn:
            c.setFillColor(WOOD_CUT)
            c.setStrokeColor(INK)
            c.rect(xx * mm, yy * mm, L * k * mm, 3.2 * mm, stroke=1, fill=1)
            c.setFillColor(INK)
            c.setFont(F, 4.4)
            if L * k > 8:
                c.drawCentredString((xx + L * k / 2) * mm, (yy + 0.9) * mm, '%s · %d' % (pos_of[round(L)], round(L)))
            xx += (L + 5) * k
        c.restoreState()
    para(c, x0, y - 4.6 - len(b3) * 4.4 - 2, 148,
         'Брать брусок <b>сухой</b>, ровный, без гнили; сорт ВС подходит — каркас закрыт листом. '
         'Обрезки — на проставки к стене дома. '
         'Профнастил — 4 листа с нарезкой в размер на заводе, схема — лист 8.', PSs)


