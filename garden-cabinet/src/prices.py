def rnd(x, step=10):
    return int(math.ceil(x / step) * step) if x else 0


def totals():
    G = groups()
    by_group = []
    for g, rows in G:
        s = sum(rnd(q * p) for (_, _, q, p, _, _) in rows)
        by_group.append((g, s))
    sub = sum(s for _, s in by_group)
    reserve = rnd(sub * RESERVE, 100)
    total = sub + DELIVERY + reserve
    return by_group, sub, reserve, total


