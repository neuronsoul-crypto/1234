def rnd(x, step=10):
    return int(math.ceil(x / step) * step) if x else 0


def totals():
    by_group = []
    for g, rows in groups():
        by_group.append((g, sum(rnd(q * p) for (_, _, q, p, _, _) in rows)))
    sub = sum(s for _, s in by_group)
    reserve = rnd(sub * RESERVE, 100)
    return by_group, sub, reserve, sub + DELIVERY + reserve


